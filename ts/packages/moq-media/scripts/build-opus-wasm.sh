#!/usr/bin/env bash
# Builds libopus's decoder to WebAssembly and writes it, base64, into src/opus-decoder-wasm.ts: the decoder the
# audio player conceals lost Opus frames with (packet-loss concealment, and in-band FEC from the next frame), which
# WebCodecs' AudioDecoder cannot do. Nothing runs this during a build or a check: the generated module is committed,
# like the worklet source, and tests/opus-decoder.test.ts checks its bytes against the hash recorded in it.
#
# Needs clang with the wasm32 target and wasm-ld (Ubuntu: clang, lld), curl and sha256sum. Every input is pinned by
# SHA-256: libopus's release tarball, and wasi-sdk's sysroot and compiler-rt builtins (libc and libm for wasm32; the
# module imports nothing, so no WASI runtime is involved). The output depends on the clang version too, which the
# generated header records.
#
#   packages/moq-media/scripts/build-opus-wasm.sh [WORKDIR]
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
out="$here/../src/opus-decoder-wasm.ts"
work=${1:-$(mktemp -d)}
mkdir -p "$work"
cd "$work"

OPUS_VERSION=1.5.2
OPUS_URL="https://downloads.xiph.org/releases/opus/opus-$OPUS_VERSION.tar.gz"
OPUS_SHA256=65c1d2f78b9f2fb20082c38cbe47c951ad5839345876e46941612ee87f9a7ce1
WASI_SDK=25
SYSROOT_URL="https://github.com/WebAssembly/wasi-sdk/releases/download/wasi-sdk-$WASI_SDK/wasi-sysroot-$WASI_SDK.0.tar.gz"
SYSROOT_SHA256=d09c62c18efcddffe4b2fdd8c5830109cc8e36130cdbc9acdc0bd1b204c942bb
BUILTINS_URL="https://github.com/WebAssembly/wasi-sdk/releases/download/wasi-sdk-$WASI_SDK/libclang_rt.builtins-wasm32-wasi-$WASI_SDK.0.tar.gz"
BUILTINS_SHA256=13aca55665321200b9659b292615adf5110ace9e891ab94511badd970553ca18

fetch() {
  local url=$1 sha=$2 file
  file=$(basename "$url")
  [ -f "$file" ] || curl -fsSL -o "$file" "$url"
  echo "$sha  $file" | sha256sum -c --quiet
  tar xzf "$file"
}
fetch "$OPUS_URL" "$OPUS_SHA256"
fetch "$SYSROOT_URL" "$SYSROOT_SHA256"
fetch "$BUILTINS_URL" "$BUILTINS_SHA256"

# clang looks for the builtins under its resource directory: give it one with wasi-sdk's.
resource=$work/resource
mkdir -p "$resource/lib/wasm32-unknown-wasip1"
cp "libclang_rt.builtins-wasm32-wasi-$WASI_SDK.0/libclang_rt.builtins-wasm32.a" \
  "$resource/lib/wasm32-unknown-wasip1/libclang_rt.builtins.a"
cp -r "$(clang -print-resource-dir)/include" "$resource/include"

cat > shim.c <<'EOF'
/* The decoder surface @mux/moq-media uses. */
#include <stdlib.h>
#include "opus.h"

OpusDecoder *mux_opus_create(int sample_rate, int channels) {
  int error = 0;
  OpusDecoder *decoder = opus_decoder_create(sample_rate, channels, &error);
  return error == OPUS_OK ? decoder : NULL;
}
/* len 0 asks for packet-loss concealment of frame_size samples; fec 1 decodes the in-band FEC (LBRR) that data
   carries for the frame before it. Returns samples per channel, or a negative libopus error. */
int mux_opus_decode(OpusDecoder *decoder, const unsigned char *data, int len, float *pcm, int frame_size, int fec) {
  return opus_decode_float(decoder, len > 0 ? data : NULL, len, pcm, frame_size, fec);
}
int mux_opus_reset(OpusDecoder *decoder) { return opus_decoder_ctl(decoder, OPUS_RESET_STATE); }
int mux_opus_has_lbrr(const unsigned char *data, int len) { return opus_packet_has_lbrr(data, len); }
void mux_opus_destroy(OpusDecoder *decoder) { opus_decoder_destroy(decoder); }
void *mux_opus_malloc(int size) { return malloc(size); }
void mux_opus_free(void *pointer) { free(pointer); }
EOF

cd "opus-$OPUS_VERSION"
sources() { sed -n "/^$1 *=/,/^\$/p" "$2" | sed 's/\\$//' | tr ' ' '\n' | grep '\.c$'; }
# Every source of the float build; the linker keeps what the decoder reaches (the encoder is dropped).
src="$(sources CELT_SOURCES celt_sources.mk) $(sources SILK_SOURCES silk_sources.mk) \
  $(sources SILK_SOURCES_FLOAT silk_sources.mk) $(sources OPUS_SOURCES opus_sources.mk) \
  $(sources OPUS_SOURCES_FLOAT opus_sources.mk)"
exports=mux_opus_create,mux_opus_decode,mux_opus_reset,mux_opus_has_lbrr,mux_opus_destroy,mux_opus_malloc,mux_opus_free
flags=(--target=wasm32-wasip1 "--sysroot=$work/wasi-sysroot-$WASI_SDK.0" "-resource-dir=$resource" -Os -flto
  -DOPUS_BUILD -DVAR_ARRAYS -DHAVE_LRINTF -DHAVE_LRINT -DNDEBUG -Iinclude -Icelt -Isilk -Isilk/float -I.)
# shellcheck disable=SC2086
clang "${flags[@]}" -w -nostartfiles -Wl,--no-entry -Wl,--gc-sections -Wl,--strip-all -Wl,-z,stack-size=65536 \
  "-Wl,--export=${exports//,/,--export=}" -o "$work/opus-decoder.wasm" ../shim.c $src

wasm=$work/opus-decoder.wasm
sha=$(sha256sum "$wasm" | cut -d' ' -f1)
clang_version=$(clang --version | head -1)
{
  echo '// Generated by scripts/build-opus-wasm.sh: do not edit. libopus, BSD-3-Clause (see NOTICE).'
  echo "// libopus $OPUS_VERSION ($OPUS_SHA256), decoder only, float, -Os;"
  echo "// wasi-sdk $WASI_SDK sysroot ($SYSROOT_SHA256) and builtins ($BUILTINS_SHA256); $clang_version."
  echo '// Imports nothing; exports memory and mux_opus_{create,decode,reset,has_lbrr,destroy,malloc,free}.'
  echo ''
  echo '/** SHA-256 of the WebAssembly module below. */'
  echo "export const OPUS_DECODER_WASM_SHA256 = '$sha';"
  echo ''
  echo '/** libopus decoder as a WebAssembly module, base64. */'
  echo "export const OPUS_DECODER_WASM_BASE64 ="
  echo "  '$(base64 -w0 "$wasm")';"
} > "$out"
echo "wrote $out: $(stat -c %s "$wasm") bytes, sha256 $sha"
